//  Mientras
let i = 0
while (i < 5){
    console.log(i);
    ++i;
}
console.log('Fin de la ejecucion del ciclo Mientras');
console.warn('---');

//  Repetir
i = 0;
do{
    console.log(i);
    ++i;
} while (i < 5);
console.log('Fin de la ejecucion del ciclo Repetir');
console.warn('---');

//  Para
for (i = 0; i < 5; i++) {
    console.log(i);

};
console.log('Fin de la ejecucion del ciclo For');
console.warn('---');
